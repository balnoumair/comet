#[derive(Debug, thiserror::Error)]
pub enum HarnessError {
    #[error("harness binary not found: {0}")]
    NotInstalled(String),
    #[error("harness protocol error: {0}")]
    Protocol(String),
    #[error("adapter install failed: {0}")]
    Install(String),
    #[error("io: {0}")]
    Io(#[from] std::io::Error),
}

